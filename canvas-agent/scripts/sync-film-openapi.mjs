import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const canvasAgentRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const openApiPath = process.env.FILMOS_OPENAPI_PATH
    ? path.resolve(process.env.FILMOS_OPENAPI_PATH)
    : path.resolve(canvasAgentRoot, "../film-contracts/openapi.json");
const outputPath = path.resolve(canvasAgentRoot, "src/film/generated/openapi-contract.ts");

const toolMappings = {
    film_project_get_context: {
        method: "get",
        path: "/projects/{hostProjectId}/context",
        operationId: "filmProjectContextGet",
        parameters: [{ mcpName: "host_project_id", openApiName: "hostProjectId", in: "path" }],
    },
    film_entity_get: {
        method: "get",
        path: "/entities/{filmEntityId}",
        operationId: "filmEntityGet",
        parameters: [{ mcpName: "film_entity_id", openApiName: "filmEntityId", in: "path" }],
    },
    film_audit_events_get: {
        method: "get",
        path: "/audit-events",
        operationId: "filmAuditEventsGet",
        parameters: [
            { mcpName: "target_id", openApiName: "targetId", in: "query" },
            { mcpName: "limit", openApiName: "limit", in: "query" },
        ],
    },
    film_command_preview: {
        method: "post",
        path: "/commands/preview",
        operationId: "filmCommandPreview",
        requestBody: true,
    },
    film_command_apply: {
        method: "post",
        path: "/commands/apply",
        operationId: "filmCommandApply",
        requestBody: true,
    },
};

const expectedActorKinds = ["human", "codex", "deepseek", "claude", "local_model", "system"];
const expectedCommandTypes = ["entity.create", "entity.set_states"];
const openApi = JSON.parse(fs.readFileSync(openApiPath, "utf8"));

const actorKinds = requireStringArray(openApi.components?.schemas?.ActorKind?.enum, "components.schemas.ActorKind.enum");
assertExact(actorKinds, expectedActorKinds, "ActorKind enum");

const tools = {};
let commandTypes;
for (const [toolName, mapping] of Object.entries(toolMappings)) {
    const operation = openApi.paths?.[mapping.path]?.[mapping.method];
    if (!operation || typeof operation !== "object") fail(`${mapping.method.toUpperCase()} ${mapping.path} is missing`);
    if (operation.operationId !== mapping.operationId) {
        fail(`${toolName} operationId drifted: expected ${mapping.operationId}, got ${String(operation.operationId)}`);
    }
    if (operation["x-implementation-state"] !== "implemented") fail(`${toolName} must map to an implemented operation`);
    const parameters = (mapping.parameters ?? []).map((expected) => {
        const parameter = (operation.parameters ?? []).find((item) => item?.name === expected.openApiName && item?.in === expected.in);
        if (!parameter) fail(`${toolName} parameter ${expected.in}:${expected.openApiName} is missing`);
        return {
            mcp_name: expected.mcpName,
            openapi_name: expected.openApiName,
            in: expected.in,
            required: parameter.required === true,
            schema: summarizeSchema(parameter.schema, `${toolName}.${expected.mcpName}`),
        };
    });
    const entry = {
        method: mapping.method.toUpperCase(),
        path: mapping.path,
        operation_id: operation.operationId,
        implementation_state: operation["x-implementation-state"],
        parameters,
    };
    if (mapping.requestBody) {
        const schema = operation.requestBody?.content?.["application/json"]?.schema;
        const refs = requireStringArray(
            schema?.anyOf?.map((item) => item?.$ref),
            `${toolName} requestBody command refs`,
        );
        const operationCommandTypes = refs.map((reference) => commandTypeFromReference(openApi, reference));
        assertExact(operationCommandTypes, expectedCommandTypes, `${toolName} command types`);
        if (commandTypes) assertExact(operationCommandTypes, commandTypes, `${toolName} shared command types`);
        commandTypes = operationCommandTypes;
        entry.request_body = {
            required: operation.requestBody.required === true,
            command_schema_refs: refs,
            command_types: operationCommandTypes,
        };
    }
    tools[toolName] = entry;
}

validateRequiredParameterShapes(tools);

const contract = {
    schema_version: 1,
    source: "film-contracts/openapi.json",
    actor_kinds: actorKinds,
    command_types: commandTypes ?? [],
    tools,
};
const rendered = `// Generated by scripts/sync-film-openapi.mjs. Do not edit by hand.\n\nexport const filmMcpOpenApiContract = ${JSON.stringify(contract, null, 2)} as const;\n\nexport const filmActorKindsFromOpenApi = filmMcpOpenApiContract.actor_kinds;\nexport const filmCommandTypesFromOpenApi = filmMcpOpenApiContract.command_types;\nexport const filmToolNamesFromOpenApi = ${JSON.stringify(Object.keys(tools))} as const;\n`;

if (process.argv.includes("--check")) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
    if (current !== rendered) fail(`generated contract is stale; run: cd canvas-agent && npm run sync:film-openapi`);
} else {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, rendered);
}

function commandTypeFromReference(document, reference) {
    const schema = resolveLocalReference(document, reference);
    const commandType = schema?.properties?.command_type?.const;
    const actorReference = schema?.properties?.actor_kind?.$ref;
    if (actorReference !== "#/components/schemas/ActorKind") fail(`${reference} actor_kind must reference ActorKind`);
    if (schema?.additionalProperties !== false) fail(`${reference} must reject additional properties`);
    if (typeof commandType !== "string" || !commandType) fail(`${reference} command_type const is missing`);
    return commandType;
}

function resolveLocalReference(document, reference) {
    if (typeof reference !== "string" || !reference.startsWith("#/")) fail(`unsupported OpenAPI reference: ${String(reference)}`);
    return reference.slice(2).split("/").reduce((value, segment) => value?.[segment.replaceAll("~1", "/").replaceAll("~0", "~")], document);
}

function summarizeSchema(schema, label) {
    if (!schema || typeof schema !== "object") fail(`${label} schema is missing`);
    const alternatives = Array.isArray(schema.anyOf) ? schema.anyOf : [schema];
    const nonNull = alternatives.filter((item) => item?.type !== "null");
    if (nonNull.length !== 1) fail(`${label} schema must have exactly one non-null shape`);
    const source = nonNull[0];
    return Object.fromEntries(
        Object.entries({
            type: source.type,
            format: source.format,
            minimum: source.minimum,
            maximum: source.maximum,
            nullable: alternatives.length !== nonNull.length || undefined,
        }).filter(([, value]) => value !== undefined),
    );
}

function validateRequiredParameterShapes(result) {
    const project = result.film_project_get_context.parameters[0];
    assertObject(project, { mcp_name: "host_project_id", openapi_name: "hostProjectId", in: "path", required: true }, "project parameter");
    assertObject(project.schema, { type: "string" }, "project parameter schema");
    const entity = result.film_entity_get.parameters[0];
    assertObject(entity, { mcp_name: "film_entity_id", openapi_name: "filmEntityId", in: "path", required: true }, "entity parameter");
    assertObject(entity.schema, { type: "string", format: "uuid4" }, "entity parameter schema");
    const [target, limit] = result.film_audit_events_get.parameters;
    assertObject(target, { mcp_name: "target_id", openapi_name: "targetId", in: "query", required: false }, "audit target parameter");
    assertObject(target.schema, { type: "string", format: "uuid4", nullable: true }, "audit target schema");
    assertObject(limit, { mcp_name: "limit", openapi_name: "limit", in: "query", required: false }, "audit limit parameter");
    assertObject(limit.schema, { type: "integer", minimum: 1, maximum: 500 }, "audit limit schema");
    for (const name of ["film_command_preview", "film_command_apply"]) {
        if (result[name].request_body?.required !== true) fail(`${name} command request body must be required`);
    }
}

function assertObject(actual, expected, label) {
    for (const [key, value] of Object.entries(expected)) {
        if (actual?.[key] !== value) fail(`${label} ${key} drifted: expected ${String(value)}, got ${String(actual?.[key])}`);
    }
}

function requireStringArray(value, label) {
    if (!Array.isArray(value) || !value.length || value.some((item) => typeof item !== "string" || !item)) fail(`${label} must be a non-empty string array`);
    return value;
}

function assertExact(actual, expected, label) {
    if (JSON.stringify(actual) !== JSON.stringify(expected)) fail(`${label} drifted: expected ${JSON.stringify(expected)}, got ${JSON.stringify(actual)}`);
}

function fail(message) {
    throw new Error(`Film OpenAPI -> MCP gate failed: ${message}`);
}
